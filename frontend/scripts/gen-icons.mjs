// Scans the app for lucide icon names and writes src/app/core/icons.ts so only used icons are bundled.
// Run: node scripts/gen-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const avail = new Set(fs.readdirSync('node_modules/lucide-angular/icons').filter((f) => f.endsWith('.d.ts')).map((f) => f.replace('.d.ts', '')));
const pascal = (s) => s.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.(ts|html)$/.test(f) && !p.endsWith('icons.ts')) files.push(p);
  }
})('src/app');

const found = new Set();
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"]/g)) if (avail.has(m[1])) found.add(m[1]);
}
// Static name="..." bindings must exist in lucide; a typo or a renamed icon fails the run instead of erroring at runtime.
const missing = new Set();
for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(/<lucide-icon[^>]*\sname="([a-z0-9-]+)"/g)) if (!avail.has(m[1])) missing.add(`${m[1]} (${f})`);
if (missing.size) { console.error(`Unknown lucide icons:\n  ${[...missing].join('\n  ')}`); process.exit(1); }
const names = [...found].sort();
const list = names.map((n) => `  ${pascal(n)},`).join('\n');
fs.writeFileSync('src/app/core/icons.ts',
  `// Generated by scripts/gen-icons.mjs from the icon names used in the app. Only these ship in the bundle.\nimport {\n${list}\n} from 'lucide-angular';\n\nexport const APP_ICONS = {\n${list}\n};\n`);
console.log(`${names.length} icons`);
